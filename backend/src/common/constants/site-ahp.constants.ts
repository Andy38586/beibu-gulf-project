//     0.20——现状用地兼容性是用地适宜性主判据）；
//   ·交通可达 ← route 域 pgRouting（项目既有）+ 刘文道路因子；
//   ·需求引力 ← forecast 域吞吐量预测 + 运河情景增量（黄文宏观需求层）。

